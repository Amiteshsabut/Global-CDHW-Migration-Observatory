/* Global Compound Drought–Heatwave Migration Observatory
   Static GitHub Pages frontend.
   Expected files are generated by scripts/prepare_dashboard_data.py.
*/

const state = {
  summary: null,
  mode: "compare",
  splitPct: 50,
  maps: {},
  basemaps: {},
  migrationRasters: {},
  migrationLayers: {},
  contextRasters: {},
  contextLayers: {},
  activeContext: "none",
  migrationOpacity: 0.85,
  contextOpacity: 0.35,
  annualChart: null,
  syncLock: false,
};

const REGION_BOUNDS = {
  "Global": [[-60, -180], [85, 180]],
  "North America": [[5, -170], [82, -50]],
  "South America": [[-58, -92], [15, -30]],
  "Europe": [[34, -25], [72, 45]],
  "Africa": [[-38, -20], [38, 55]],
  "Asia": [[-10, 25], [82, 180]],
  "Oceania": [[-50, 105], [5, 180]],
};

const PALETTES = {
  migration: ["#e6f6f3", "#bde8e0", "#79c8bc", "#2aa394", "#14766f", "#0b4f4b", "#062f2d"],
  differenceNeg: ["#313695", "#4575b4", "#74add1", "#abd9e9"],
  differencePos: ["#fdae61", "#f46d43", "#d73027", "#a50026"],
  population: ["#f7f7f7", "#d9d9d9", "#bdbdbd", "#969696", "#636363", "#252525"],
  cropland: ["#f7fcf5", "#c7e9c0", "#74c476", "#31a354", "#006d2c"],
  pasture: ["#fff7ec", "#fee8c8", "#fdbb84", "#e34a33", "#7f0000"],
};

document.addEventListener("DOMContentLoaded", init);

async function init() {
  setupMaps();
  bindControls();
  setupDivider();
  try {
    setStatus("Loading data…");
    state.summary = await fetchJSON("data/summary.json");
    renderSummary();
    renderAnnualChart();
    await loadPrimaryRasters();
    await renderMode();
    setStatus("Ready");
  } catch (error) {
    console.error(error);
    setStatus("Data not prepared", true);
    showToast(
      "Dashboard shell is ready, but data/summary.json or processed rasters are missing. Run scripts/prepare_dashboard_data.py first."
    );
  }
}

function setupMaps() {
  const opts = {
    center: [24, 0],
    zoom: 2,
    minZoom: 1,
    maxZoom: 8,
    worldCopyJump: false,
    zoomControl: true,
    preferCanvas: true,
  };

  state.maps.left = L.map("mapLeft", opts);
  state.maps.right = L.map("mapRight", {
    ...opts,
    zoomControl: false,
    attributionControl: false,
    dragging: false,
    scrollWheelZoom: false,
    doubleClickZoom: false,
    boxZoom: false,
    keyboard: false,
    touchZoom: false,
  });

  const tileUrl = "https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png";
  const tileOpts = {
    attribution: "&copy; OpenStreetMap contributors",
    maxZoom: 19,
  };

  state.basemaps.left = L.tileLayer(tileUrl, tileOpts).addTo(state.maps.left);
  state.basemaps.right = L.tileLayer(tileUrl, tileOpts).addTo(state.maps.right);

  state.maps.left.fitBounds(REGION_BOUNDS.Global, { padding: [8, 8] });
  syncRightMap();

  state.maps.left.on("move zoom", syncRightMap);
  state.maps.left.on("mousemove", updateMouseReadout);
  state.maps.left.on("click", inspectPixel);
}

function syncRightMap() {
  if (state.syncLock) return;
  state.syncLock = true;
  state.maps.right.setView(
    state.maps.left.getCenter(),
    state.maps.left.getZoom(),
    { animate: false, reset: true }
  );
  state.syncLock = false;
}

function bindControls() {
  document.querySelectorAll('input[name="extentMode"]').forEach((radio) => {
    radio.addEventListener("change", () => {
      const regionMode = radio.value === "region" && radio.checked;
      document.getElementById("regionSelect").disabled = !regionMode;
      if (!regionMode && radio.checked) {
        document.getElementById("regionSelect").value = "Global";
        zoomToRegion("Global");
      }
    });
  });

  document.getElementById("regionSelect").addEventListener("change", (event) => {
    zoomToRegion(event.target.value);
  });

  document.querySelectorAll(".mode-btn").forEach((btn) => {
    btn.addEventListener("click", async () => {
      document.querySelectorAll(".mode-btn").forEach((b) => b.classList.remove("active"));
      btn.classList.add("active");
      state.mode = btn.dataset.mode;
      await renderMode();
    });
  });

  document.getElementById("contextSelect").addEventListener("change", async (event) => {
    state.activeContext = event.target.value;
    await renderContext();
  });

  document.getElementById("migrationOpacity").addEventListener("input", (event) => {
    state.migrationOpacity = Number(event.target.value) / 100;
    document.getElementById("migrationOpacityValue").textContent = `${event.target.value}%`;
    Object.values(state.migrationLayers).forEach((layer) => {
      if (layer && layer.setOpacity) layer.setOpacity(state.migrationOpacity);
    });
  });

  document.getElementById("contextOpacity").addEventListener("input", (event) => {
    state.contextOpacity = Number(event.target.value) / 100;
    document.getElementById("contextOpacityValue").textContent = `${event.target.value}%`;
    Object.values(state.contextLayers).forEach((layer) => {
      if (layer && layer.setOpacity) layer.setOpacity(state.contextOpacity);
    });
  });

  document.getElementById("showBasemap").addEventListener("change", (event) => {
    const show = event.target.checked;
    ["left", "right"].forEach((side) => {
      const map = state.maps[side];
      const layer = state.basemaps[side];
      if (show && !map.hasLayer(layer)) layer.addTo(map);
      if (!show && map.hasLayer(layer)) map.removeLayer(layer);
    });
  });

  document.getElementById("btnResetView").addEventListener("click", () => {
    document.querySelector('input[name="extentMode"][value="global"]').checked = true;
    document.getElementById("regionSelect").disabled = true;
    document.getElementById("regionSelect").value = "Global";
    zoomToRegion("Global");
    setSplit(50);
  });
}

function setupDivider() {
  const divider = document.getElementById("divider");
  const shell = document.getElementById("mapShell");
  let dragging = false;

  divider.addEventListener("pointerdown", (event) => {
    dragging = true;
    divider.setPointerCapture(event.pointerId);
  });

  divider.addEventListener("pointermove", (event) => {
    if (!dragging || state.mode !== "compare") return;
    const rect = shell.getBoundingClientRect();
    const pct = ((event.clientX - rect.left) / rect.width) * 100;
    setSplit(Math.max(5, Math.min(95, pct)));
  });

  divider.addEventListener("pointerup", (event) => {
    dragging = false;
    try { divider.releasePointerCapture(event.pointerId); } catch (_) {}
  });

  window.addEventListener("resize", () => {
    state.maps.left.invalidateSize();
    state.maps.right.invalidateSize();
    setSplit(state.splitPct);
  });
}

function setSplit(pct) {
  state.splitPct = pct;
  const rightMap = document.getElementById("mapRight");
  const divider = document.getElementById("divider");
  rightMap.style.clipPath = `inset(0 0 0 ${pct}%)`;
  divider.style.left = `${pct}%`;
}

async function loadPrimaryRasters() {
  const earlyFile = state.summary.periods.early.file;
  const recentFile = state.summary.periods.recent.file;
  const changeFile = state.summary.change.file;

  const [early, recent, change] = await Promise.all([
    loadGeoRaster(earlyFile),
    loadGeoRaster(recentFile),
    loadGeoRaster(changeFile),
  ]);

  state.migrationRasters.early = early;
  state.migrationRasters.recent = recent;
  state.migrationRasters.change = change;
}

async function loadGeoRaster(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Could not load ${url}: ${response.status}`);
  const arrayBuffer = await response.arrayBuffer();
  return await parseGeoraster(arrayBuffer);
}

async function renderMode() {
  clearMigrationLayers();

  const rightMapEl = document.getElementById("mapRight");
  const divider = document.getElementById("divider");
  const rightLabel = document.getElementById("rightPeriodLabel");
  const leftLabel = document.getElementById("leftPeriodLabel");
  const legendMax = document.getElementById("legendMax");
  const legendRamp = document.querySelector(".legend-ramp");

  if (state.mode === "compare") {
    rightMapEl.classList.remove("hidden");
    divider.classList.remove("hidden");
    rightLabel.classList.remove("hidden");
    leftLabel.classList.remove("hidden");

    leftLabel.textContent = state.summary.periods.early.label;
    rightLabel.textContent = state.summary.periods.recent.label;

    document.getElementById("mapModeTitle").textContent = "Period comparison";
    document.getElementById("mapModeSubtitle").textContent =
      `Drag the divider to compare ${state.summary.periods.early.label} with ${state.summary.periods.recent.label}.`;

    const maxValue = state.summary.display.migration_color_max;
    legendMax.textContent = formatNumber(maxValue);
    legendRamp.style.background =
      "linear-gradient(90deg, #e6f6f3, #bde8e0, #79c8bc, #2aa394, #14766f, #0b4f4b, #062f2d)";

    state.migrationLayers.early = makeRasterLayer(
      state.migrationRasters.early,
      (value) => migrationColor(value, maxValue),
      state.migrationOpacity,
      300
    ).addTo(state.maps.left);

    state.migrationLayers.recent = makeRasterLayer(
      state.migrationRasters.recent,
      (value) => migrationColor(value, maxValue),
      state.migrationOpacity,
      300
    ).addTo(state.maps.right);

    setSplit(state.splitPct);
  } else {
    rightMapEl.classList.add("hidden");
    divider.classList.add("hidden");
    rightLabel.classList.add("hidden");
    leftLabel.classList.remove("hidden");
    leftLabel.textContent = "2001–2019 minus 1982–2000";

    document.getElementById("mapModeTitle").textContent = "Change map";
    document.getElementById("mapModeSubtitle").textContent =
      "Recent minus early cumulative migration-track count. Positive values indicate an increase.";

    const maxAbs = state.summary.display.change_color_abs_max;
    legendMax.textContent = `±${formatNumber(maxAbs)}`;
    legendRamp.style.background =
      "linear-gradient(90deg, #313695, #74add1, #e8eef3, #fdae61, #d73027, #a50026)";

    state.migrationLayers.change = makeRasterLayer(
      state.migrationRasters.change,
      (value) => differenceColor(value, maxAbs),
      state.migrationOpacity,
      300
    ).addTo(state.maps.left);
  }

  await renderContext();
}

function clearMigrationLayers() {
  Object.entries(state.migrationLayers).forEach(([key, layer]) => {
    if (!layer) return;
    ["left", "right"].forEach((side) => {
      const map = state.maps[side];
      if (map && map.hasLayer(layer)) map.removeLayer(layer);
    });
    state.migrationLayers[key] = null;
  });
}

async function renderContext() {
  clearContextLayers();
  const name = state.activeContext;
  const legend = document.getElementById("contextLegend");

  if (name === "none") {
    legend.classList.add("hidden");
    return;
  }

  const cfg = state.summary.context[name];
  if (!cfg) {
    showToast(`No configuration found for context layer: ${name}`);
    return;
  }

  if (!state.contextRasters[name]) {
    setStatus(`Loading ${name}…`);
    try {
      state.contextRasters[name] = await loadGeoRaster(cfg.file);
    } catch (error) {
      console.error(error);
      showToast(`Could not load ${name} raster. Check ${cfg.file}.`);
      setStatus("Ready");
      return;
    }
  }

  const raster = state.contextRasters[name];
  const colorFn = (value) => contextColor(value, cfg, name);

  state.contextLayers.left = makeRasterLayer(
    raster, colorFn, state.contextOpacity, 200
  ).addTo(state.maps.left);

  if (state.mode === "compare") {
    state.contextLayers.right = makeRasterLayer(
      raster, colorFn, state.contextOpacity, 200
    ).addTo(state.maps.right);
  }

  document.getElementById("contextLegendTitle").textContent = cfg.label;
  document.querySelector(".context-ramp").style.background =
    contextLegendGradient(name);
  legend.classList.remove("hidden");
  setStatus("Ready");
}

function clearContextLayers() {
  Object.entries(state.contextLayers).forEach(([key, layer]) => {
    if (!layer) return;
    ["left", "right"].forEach((side) => {
      const map = state.maps[side];
      if (map && map.hasLayer(layer)) map.removeLayer(layer);
    });
    state.contextLayers[key] = null;
  });
}

function makeRasterLayer(georaster, colorFn, opacity, zIndex = 300) {
  return new GeoRasterLayer({
    georaster,
    opacity,
    zIndex,
    resolution: 256,
    pixelValuesToColorFn: (pixelValues) => {
      const v = pixelValues?.[0];
      return colorFn(v);
    },
  });
}

function migrationColor(value, maxValue) {
  if (!Number.isFinite(value) || value <= 0 || maxValue <= 0) return null;
  const t = clamp(value / maxValue, 0, 1);
  return interpolatePalette(PALETTES.migration, t);
}

function differenceColor(value, maxAbs) {
  if (!Number.isFinite(value) || maxAbs <= 0) return null;
  if (Math.abs(value) < maxAbs * 0.01) return "rgba(255,255,255,0)";
  if (value < 0) {
    const t = clamp(Math.abs(value) / maxAbs, 0, 1);
    return interpolatePalette(PALETTES.differenceNeg.slice().reverse(), t);
  }
  const t = clamp(value / maxAbs, 0, 1);
  return interpolatePalette(PALETTES.differencePos, t);
}

function contextColor(value, cfg, name) {
  if (!Number.isFinite(value)) return null;
  const vmax = Number(cfg.display_max || 1);
  const vmin = Number(cfg.display_min || 0);

  let normalized;
  if (cfg.transform === "log1p") {
    normalized =
      (Math.log1p(Math.max(value, 0)) - Math.log1p(Math.max(vmin, 0))) /
      Math.max(1e-9, Math.log1p(Math.max(vmax, 0)) - Math.log1p(Math.max(vmin, 0)));
  } else {
    normalized = (value - vmin) / Math.max(1e-9, vmax - vmin);
  }

  const palette = PALETTES[name] || PALETTES.population;
  return interpolatePalette(palette, clamp(normalized, 0, 1));
}

function contextLegendGradient(name) {
  if (name === "population") {
    return "linear-gradient(90deg,#f7f7f7,#d9d9d9,#969696,#636363,#252525)";
  }
  if (name === "cropland") {
    return "linear-gradient(90deg,#f7fcf5,#c7e9c0,#74c476,#31a354,#006d2c)";
  }
  return "linear-gradient(90deg,#fff7ec,#fee8c8,#fdbb84,#e34a33,#7f0000)";
}

function interpolatePalette(colors, t) {
  if (t <= 0) return colors[0];
  if (t >= 1) return colors[colors.length - 1];

  const scaled = t * (colors.length - 1);
  const i = Math.floor(scaled);
  const f = scaled - i;
  const a = hexToRgb(colors[i]);
  const b = hexToRgb(colors[i + 1]);

  const r = Math.round(a.r + (b.r - a.r) * f);
  const g = Math.round(a.g + (b.g - a.g) * f);
  const bl = Math.round(a.b + (b.b - a.b) * f);

  return `rgb(${r},${g},${bl})`;
}

function hexToRgb(hex) {
  const h = hex.replace("#", "");
  return {
    r: parseInt(h.slice(0, 2), 16),
    g: parseInt(h.slice(2, 4), 16),
    b: parseInt(h.slice(4, 6), 16),
  };
}

function zoomToRegion(name) {
  const bounds = REGION_BOUNDS[name] || REGION_BOUNDS.Global;
  state.maps.left.fitBounds(bounds, { padding: [10, 10], animate: true });
}

function renderSummary() {
  const early = state.summary.periods.early.stats;
  const recent = state.summary.periods.recent.stats;

  document.getElementById("statEarlyTotal").textContent = formatNumber(early.sum);
  document.getElementById("statRecentTotal").textContent = formatNumber(recent.sum);
  document.getElementById("statRecentMax").textContent = formatNumber(recent.max);

  const pct = early.sum !== 0 ? ((recent.sum - early.sum) / early.sum) * 100 : null;
  const pctEl = document.getElementById("statChangePct");
  pctEl.textContent = pct === null ? "—" : `${pct >= 0 ? "+" : ""}${pct.toFixed(1)}%`;
}

function renderAnnualChart() {
  const rows = state.summary.annual || [];
  const labels = rows.map((d) => d.year);
  const values = rows.map((d) => d.sum);

  const ctx = document.getElementById("annualChart");
  if (state.annualChart) state.annualChart.destroy();

  state.annualChart = new Chart(ctx, {
    type: "line",
    data: {
      labels,
      datasets: [{
        label: "Annual total track count",
        data: values,
        borderColor: "#0f766e",
        backgroundColor: "rgba(15,118,110,.12)",
        fill: true,
        borderWidth: 2,
        pointRadius: 0,
        tension: 0.18,
      }],
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      animation: false,
      plugins: {
        legend: { display: false },
        tooltip: {
          callbacks: {
            label: (context) => ` ${formatNumber(context.parsed.y)}`
          }
        }
      },
      scales: {
        x: {
          grid: { display: false },
          ticks: {
            maxTicksLimit: 6,
            color: "#71808f",
            font: { size: 9 },
          },
        },
        y: {
          beginAtZero: true,
          grid: { color: "rgba(100,115,130,.12)" },
          ticks: {
            maxTicksLimit: 5,
            color: "#71808f",
            font: { size: 9 },
            callback: (v) => compactNumber(v),
          },
        },
      },
    },
  });
}

function updateMouseReadout(event) {
  const { lat, lng } = event.latlng;
  document.getElementById("mapReadout").innerHTML =
    `<strong>${lat.toFixed(2)}°, ${lng.toFixed(2)}°</strong>`;
}

function inspectPixel(event) {
  const { lat, lng } = event.latlng;
  let html = `<strong>${lat.toFixed(2)}°, ${lng.toFixed(2)}°</strong><br/>`;

  if (state.mode === "compare") {
    const early = sampleRaster(state.migrationRasters.early, lat, lng);
    const recent = sampleRaster(state.migrationRasters.recent, lat, lng);
    html += `${state.summary.periods.early.label}: ${formatMaybe(early)}<br/>`;
    html += `${state.summary.periods.recent.label}: ${formatMaybe(recent)}`;
  } else {
    const change = sampleRaster(state.migrationRasters.change, lat, lng);
    html += `Recent − early: ${formatMaybe(change)}`;
  }

  if (state.activeContext !== "none" && state.contextRasters[state.activeContext]) {
    const v = sampleRaster(state.contextRasters[state.activeContext], lat, lng);
    html += `<br/>${state.summary.context[state.activeContext].label}: ${formatMaybe(v)}`;
  }

  L.popup()
    .setLatLng(event.latlng)
    .setContent(html)
    .openOn(state.maps.left);
}

function sampleRaster(raster, lat, lng) {
  if (!raster || !raster.values || !raster.values[0]) return null;

  const xmin = raster.xmin;
  const xmax = raster.xmax;
  const ymin = raster.ymin;
  const ymax = raster.ymax;
  if (lng < xmin || lng > xmax || lat < ymin || lat > ymax) return null;

  const width = raster.width;
  const height = raster.height;
  const px = Math.floor(((lng - xmin) / (xmax - xmin)) * width);
  const py = Math.floor(((ymax - lat) / (ymax - ymin)) * height);

  if (px < 0 || py < 0 || px >= width || py >= height) return null;
  const value = raster.values[0][py][px];
  return Number.isFinite(value) ? value : null;
}

function setStatus(text, isError = false) {
  const el = document.getElementById("mapStatus");
  el.textContent = text;
  el.classList.toggle("error", isError);
}

function showToast(message, ms = 6500) {
  const toast = document.getElementById("toast");
  toast.textContent = message;
  toast.classList.remove("hidden");
  clearTimeout(showToast._timer);
  showToast._timer = setTimeout(() => toast.classList.add("hidden"), ms);
}

async function fetchJSON(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Could not load ${url}: ${response.status}`);
  return await response.json();
}

function formatMaybe(value) {
  if (value === null || value === undefined || !Number.isFinite(value)) return "No data";
  return formatNumber(value);
}

function formatNumber(value) {
  if (!Number.isFinite(Number(value))) return "—";
  const n = Number(value);
  if (Math.abs(n) >= 1e9) return `${(n / 1e9).toFixed(2)}B`;
  if (Math.abs(n) >= 1e6) return `${(n / 1e6).toFixed(2)}M`;
  if (Math.abs(n) >= 1e3) return `${(n / 1e3).toFixed(1)}k`;
  if (Math.abs(n) >= 100) return n.toFixed(0);
  if (Math.abs(n) >= 10) return n.toFixed(1);
  return n.toFixed(2);
}

function compactNumber(value) {
  const n = Number(value);
  if (Math.abs(n) >= 1e9) return `${(n / 1e9).toFixed(1)}B`;
  if (Math.abs(n) >= 1e6) return `${(n / 1e6).toFixed(1)}M`;
  if (Math.abs(n) >= 1e3) return `${(n / 1e3).toFixed(0)}k`;
  return `${n}`;
}

function clamp(v, lo, hi) {
  return Math.max(lo, Math.min(hi, v));
}
